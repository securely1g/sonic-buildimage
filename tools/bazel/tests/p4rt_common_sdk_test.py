#!/usr/bin/env python3
"""Check SDK refresh, architecture checks and safe failure before P4RT builds."""

import io
import json
from pathlib import Path
import platform
import struct
import subprocess
import sys
import tarfile
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from tools.bazel.p4rt_common_sdk import build_sdk, prepare_repository


class P4rtCommonSdkTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.source = self.root / "common source"
        self.source.mkdir()
        self.archive = self.source / "sdk.tar"
        self.output = self.root / "sdk output"
        self.arch = "arm64" if platform.machine() == "aarch64" else "amd64"
        self.sdk_archive()

    def sdk_archive(self, *, arch=None, revision="one", extra=None, omit=None):
        elf = bytearray(64)
        elf[:6] = b"\x7fELF\x02\x01"
        struct.pack_into("<H", elf, 18, {"amd64": 62, "arm64": 183}[arch or self.arch])
        files = {
            "lib/libswsscommon.so.0": bytes(elf),
            "include/swss/dbconnector.h": revision.encode(),
            "include/swss/cfg_schema.h": b"// generated YANG schema\n",
        }
        files.update(extra or {})
        files.pop(omit, None)
        with tarfile.open(self.archive, "w") as package:
            for name, data in files.items():
                member = tarfile.TarInfo(name)
                member.size = len(data)
                package.addfile(member, io.BytesIO(data))

    def prepare(self):
        prepare_repository(self.archive, self.output, self.arch, {"producer_bazel_version": "8.5.1"})

    def fake_bazel(self, version="bazel 8.5.1"):
        (self.source / "version-output").write_text(version + "\n")
        (self.source / "MODULE.bazel").write_text('module(name="common")\n')
        subprocess.run(["git", "init", "-q", str(self.source)], check=True)
        subprocess.run(["git", "-C", str(self.source), "add", "MODULE.bazel"], check=True)
        subprocess.run(["git", "-C", str(self.source), "-c", "user.name=SDK test",
                        "-c", "user.email=sdk-test@example.invalid", "commit", "-qm", "test source"], check=True)
        bazel = self.root / "bazel"
        bazel.write_text('''#!/usr/bin/env python3
import json, os, pathlib, sys
root = pathlib.Path.cwd()
assert os.environ["USE_BAZEL_VERSION"] == "8.5.1"
with (root / "calls.jsonl").open("a") as calls:
    calls.write(json.dumps(sys.argv[1:]) + "\\n")
command = sys.argv[2]
if command == "version":
    print((root / "version-output").read_text().strip())
elif command == "build" and (root / "fail-build").exists():
    sys.exit(1)
elif command == "cquery":
    print("bazel-out/sdk.tar" if (root / "relative-output").exists() else root / "sdk.tar")
elif command == "info":
    assert "--platforms=" in sys.argv
    print(root / "execution-root")
''')
        bazel.chmod(0o755)
        return str(bazel)

    def test_replacing_sdk_removes_old_headers_and_preserves_both_entry_points(self):
        self.sdk_archive(extra={"include/swss/removed.h": b"old"})
        self.prepare()
        self.sdk_archive(revision="two")
        self.prepare()
        self.assertFalse((self.output / "include/swss/removed.h").exists())
        self.assertEqual((self.output / "include/swss/dbconnector.h").read_text(), "two")
        build = (self.output / "BUILD.bazel").read_text()
        self.assertIn('name = "common"', build)
        self.assertIn('name = "libswsscommon"', build)
        self.assertIn('shared_library = "lib/libswsscommon.so.0"', build)
        self.assertNotIn("srcs =", build)

    def test_wrong_architecture_does_not_replace_existing_sdk(self):
        self.prepare()
        self.sdk_archive(arch="arm64" if self.arch == "amd64" else "amd64", revision="wrong")
        with self.assertRaisesRegex(ValueError, "little-endian"):
            self.prepare()
        self.assertEqual((self.output / "include/swss/dbconnector.h").read_text(), "one")

    def test_missing_generated_schema_is_rejected(self):
        self.sdk_archive(omit="include/swss/cfg_schema.h")
        with self.assertRaisesRegex(ValueError, "cfg_schema.h"):
            self.prepare()
        self.assertFalse(self.output.exists())

    def test_source_files_cannot_leak_into_the_binary_repository(self):
        self.sdk_archive(extra={"common/dbconnector.cpp": b"not an SDK input"})
        with self.assertRaisesRegex(ValueError, "not Common sources"):
            self.prepare()

    def test_unrelated_output_directory_is_preserved(self):
        self.output.mkdir()
        (self.output / "important.txt").write_text("keep")
        with self.assertRaisesRegex(ValueError, "not generated by this tool"):
            self.prepare()
        self.assertEqual((self.output / "important.txt").read_text(), "keep")

    def test_existing_sdk_does_not_skip_bazel_source_validation(self):
        bazel = self.fake_bazel()
        build_sdk(self.source, self.output, self.arch, bazel)
        self.sdk_archive(revision="two")
        build_sdk(self.source, self.output, self.arch, bazel)
        calls = [json.loads(line) for line in (self.source / "calls.jsonl").read_text().splitlines()]
        self.assertEqual(sum(call[1] == "build" for call in calls), 2)
        self.assertEqual(sum(call[1] == "shutdown" for call in calls), 2)
        for call in calls:
            if call[1] in ("build", "cquery"):
                self.assertIn("--//tools/bazel:yang_modules=True", call)
        self.assertEqual((self.output / "include/swss/dbconnector.h").read_text(), "two")
        receipt = json.loads((self.output / "sdk-build.json").read_text())
        self.assertEqual(receipt["architecture"], self.arch)
        self.assertEqual(receipt["producer_bazel_version"], "8.5.1")
        self.assertTrue(receipt["yang_modules"])

    def test_failed_producer_does_not_fall_back_to_the_old_sdk(self):
        bazel = self.fake_bazel()
        build_sdk(self.source, self.output, self.arch, bazel)
        (self.source / "fail-build").touch()
        with self.assertRaises(subprocess.CalledProcessError):
            build_sdk(self.source, self.output, self.arch, bazel)
        self.assertEqual((self.output / "include/swss/dbconnector.h").read_text(), "one")
        calls = [json.loads(line) for line in (self.source / "calls.jsonl").read_text().splitlines()]
        self.assertEqual(calls[-1][1], "shutdown")

    def test_bazelisk_banner_does_not_hide_the_producer_version(self):
        bazel = self.fake_bazel("Bazelisk v1.29.0\nbazel 8.5.1")
        build_sdk(self.source, self.output, self.arch, bazel)
        self.assertTrue((self.output / "lib/libswsscommon.so.0").is_file())

    def test_wrong_version_is_rejected_even_with_bazelisk_banner(self):
        bazel = self.fake_bazel("Bazelisk v1.29.0\nbazel 6.4.0")
        with self.assertRaisesRegex(ValueError, "must build with Bazel 8.5.1"):
            build_sdk(self.source, self.output, self.arch, bazel)
        calls = [json.loads(line) for line in (self.source / "calls.jsonl").read_text().splitlines()]
        self.assertFalse(any(call[1] == "build" for call in calls))

    def test_sdk_lookup_uses_the_private_execution_root(self):
        bazel = self.fake_bazel()
        private_output = self.source / "execution-root/bazel-out"
        private_output.mkdir(parents=True)
        self.archive.rename(private_output / "sdk.tar")
        other_output = self.root / "another-build-output"
        other_output.mkdir()
        (other_output / "sdk.tar").write_text("not this build's SDK")
        (self.source / "bazel-out").symlink_to(other_output, target_is_directory=True)
        (self.source / "relative-output").touch()
        build_sdk(self.source, self.output, self.arch, bazel)
        self.assertEqual((self.output / "include/swss/dbconnector.h").read_text(), "one")

    def test_make_cache_tracks_the_helper_and_import_template(self):
        repository = Path(__file__).resolve().parents[3]
        makefile = """SONIC_P4RT := p4rt.deb
p4rt.deb_SRC_PATH := src/sonic-p4rt
include rules/p4rt.dep
.PHONY: print-inputs
print-inputs:
\t@printf '%s\\n' $(p4rt.deb_DEP_FILES)
"""
        result = subprocess.run(["make", "--no-print-directory", "-s", "-f", "-", "print-inputs"],
                                input=makefile, text=True, capture_output=True,
                                cwd=repository, check=True)
        inputs = result.stdout.splitlines()
        self.assertIn("tools/bazel/p4rt_common_sdk.py", inputs)
        self.assertIn("src/sonic-p4rt/common-sdk.BUILD.bazel", inputs)
        self.assertTrue(all((repository / name).is_file() for name in inputs), inputs)


if __name__ == "__main__":
    unittest.main()
