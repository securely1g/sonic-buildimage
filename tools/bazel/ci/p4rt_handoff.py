"""Verify and stage the source-owned P4RT TAR interface between Bazel versions."""

import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

from tools.bazel.ci import artifact_validation as check

FILES = ('p4rt_runtime.tar', 'p4rt_runtime_debug.tar',
         'p4rt_runtime_contract.json', 'p4rt_runtime_debug_contract.json')
KIND = 'sonic-p4rt-owner-payload'
WORKSPACE = 'workspace(name = "p4rt_owner_payload")\n'
BUILD = 'exports_files(' + json.dumps([*FILES, 'handoff.json']) + ', visibility = ["//visibility:public"])\n'


def source_identity(source, expected):
    source = Path(source).resolve()
    check.require(re.fullmatch(r'[0-9a-f]{40}', expected), 'Expected a full P4RT source revision')
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source, text=True).strip()
    check.require(revision == expected, 'P4RT source revision differs from the selected owner')
    check.require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=source, text=True).strip(),
                  'P4RT owner checkout must be clean')
    check.require((source / '.bazelversion').read_text().strip() == '6.4.0', 'P4RT owner Bazel version changed')
    check.require((source / 'WORKSPACE.bazel').is_file() or (source / 'WORKSPACE').is_file(),
                  'Expected the actual P4RT WORKSPACE owner')
    return revision


def owner_api(source, revision):
    source_identity(source, revision)
    path = Path(source).resolve() / 'ci'
    spec = importlib.util.spec_from_file_location('selected_p4rt_handoff', path / 'production_handoff.py')
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(path))
    try:
        spec.loader.exec_module(module)
    finally:
        sys.path.pop(0)
    return module


def same_common_library(sdk, common_tar, parent_source_tar):
    """Compare deployable bytes, not a second source revision's ABI claim."""
    library_hash = check.sha(Path(sdk) / 'lib/libswsscommon.so.0')
    name = 'usr/lib/x86_64-linux-gnu/libswsscommon.so.0.0.0'
    for archive in (common_tar, parent_source_tar):
        payload = check.payload(archive)
        check.require(payload.get(name, {}).get('kind') == 'file' and
                      payload[name].get('sha256') == library_hash,
                      'Common SDK differs from the selected parent runtime: ' + str(archive))
    return {'path': name, 'sha256': library_hash,
            'common_runtime_tar_sha256': check.sha(common_tar),
            'parent_source_tar_sha256': check.sha(parent_source_tar)}


def stage(source, revision, sdk, output, destination, parent_common):
    source, sdk, output, destination = map(Path, (source, sdk, output, destination))
    api = owner_api(source, revision)
    built = api.verify_build(output, sdk, revision)
    receipt = {'schema': 1, 'kind': KIND, 'source_revision': revision,
               'producer_bazel_version': '6.4.0', 'sdk_producer_bazel_version': '8.5.1',
               'sdk_inventory': built['sdk_inventory'], 'parent_common': parent_common,
               'files': {name: {'sha256': check.sha(output / name),
                                'bytes': (output / name).stat().st_size} for name in FILES}}
    if destination.exists():
        check.require(not destination.is_symlink() and
                      (destination / 'handoff.json').is_file() and
                      json.loads((destination / 'handoff.json').read_text()).get('kind') == KIND,
                      'Refusing to replace a directory not generated by the P4RT handoff')
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.p4rt-owner-', dir=destination.parent) as temporary:
        staging = Path(temporary) / 'repository'
        staging.mkdir()
        for name in FILES:
            shutil.copyfile(output / name, staging / name)
            (staging / name).chmod(0o644)
        (staging / 'WORKSPACE.bazel').write_text(WORKSPACE)
        (staging / 'BUILD.bazel').write_text(BUILD)
        (staging / 'handoff.json').write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n')
        if destination.exists():
            shutil.rmtree(destination)
        staging.rename(destination)
    verify_stage(destination, source, revision, sdk, output)
    return receipt


def verify_stage(destination, source, revision, sdk, output):
    destination = Path(destination)
    api = owner_api(source, revision)
    built = api.verify_build(output, sdk, revision)
    receipt = json.loads((destination / 'handoff.json').read_text())
    check.require(receipt.get('kind') == KIND and receipt.get('source_revision') == revision and
                  receipt.get('sdk_inventory') == built['sdk_inventory'] and
                  set(receipt.get('files', {})) == set(FILES), 'P4RT staged owner identity differs')
    check.require({path.name for path in destination.iterdir()} ==
                  set(FILES) | {'BUILD.bazel', 'WORKSPACE.bazel', 'handoff.json'},
                  'Unexpected files in the declared owner repository')
    for name, expected in (('BUILD.bazel', BUILD), ('WORKSPACE.bazel', WORKSPACE)):
        path = destination / name
        check.require(not path.is_symlink() and path.read_text() == expected, 'Generated owner interface changed: ' + name)
    for name in FILES:
        path = destination / name
        check.require(path.is_file() and not path.is_symlink() and
                      check.sha(path) == check.sha(Path(output) / name) == receipt['files'][name]['sha256'] and
                      path.stat().st_size == receipt['files'][name]['bytes'],
                      'Staged owner output changed: ' + name)
    return receipt
