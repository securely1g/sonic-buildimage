#!/usr/bin/env python3
"""Validate the configured foreign Debian stage before SONiC source integration.

Runs in a pinned root container on native AMD64/ARM64. The shared installer
builds the filesystem; the existing image validator checks its initial state
and APT lifecycle in disposable Bubblewrap namespaces. No DEB is generated.
"""

import argparse
from functools import partial
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from tools.bazel.ci import bazel_commands, command_log, validate_dpkg_state as validation

OWNER = "//dockers/docker-base-trixie:"
ENVIRONMENT = "debian:trixie-20260918@sha256:9cc080028c43b27d2074d63a5f9caf7166d731494965616c1a6d2827a004585c"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--architecture", choices=validation.MACHINES, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--bazel", default="bazel")
    parser.add_argument("--bazel-arg", action="append", default=[])
    parser.add_argument("--execution-environment", required=True)
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    report = {"_generated": "AUTO-GENERATED by tools/bazel/ci/configured_debian.py. DO NOT EDIT MANUALLY.",
              "status": "running", "stage": "foreign_debian_only", "architecture": args.architecture, "commands": []}
    execute = partial(command_log.execute, directory=out, receipt=report, cwd=ROOT)
    try:
        machine = validation.MACHINES[args.architecture]
        validation.require(platform.machine() == machine and os.geteuid() == 0,
                           "Use the selected native root build container")
        validation.require(args.execution_environment == ENVIRONMENT, "Build container differs from declared execution environment")
        report.update(host_machine=platform.machine(), requested_execution_environment=args.execution_environment)
        report["revision"] = execute(["git", "rev-parse", "HEAD"], name="revision").strip()
        report["worktree_clean"] = not execute(["git", "status", "--porcelain"], name="source-state").strip()
        report["verification_tools"] = execute(["dpkg-query", "-W", "-f=${Package}\t${Version}\n",
            "gcc", "libarchive-tools", "python3", "git", "ca-certificates"], name="verification-tools").splitlines()
        options = ["--jobs=2", "--local_resources=cpu=2", "--lockfile_mode=update",
                   "--platforms=@sonic_build_infra//platforms:" + machine + "_trixie",
                   "--host_platform=@sonic_build_infra//platforms:" + machine + "_trixie", *args.bazel_arg]
        targets = {"rootfs.tar": OWNER + "configured_debian", "installation.json": OWNER + "configured_debian_receipt",
                   "selection.json": OWNER + "debian_runtime_selection", "base.tar.gz": OWNER + "installation_base",
                   "bwrap": "//tools/bazel/oci:bubblewrap"}
        report["action_audit"] = bazel_commands.audit_targets(args.bazel, options, list(targets.values()),
            workspace=ROOT, output=out / "action-audit.json")
        validation.require(report["action_audit"]["action_count"] > 0, "Bazel action graph is empty")
        execute([args.bazel, "build", *options, *targets.values()], name="build")
        paths = {}
        for name, target in targets.items():
            files = execute([args.bazel, "cquery", *options, "--output=files",
                             "config(" + target + ", target)"], name="locate-" + name).splitlines()
            validation.require(len(files) == 1, "Expected one output from " + target)
            paths[name] = ROOT / files[0]
        installation = json.loads(paths["installation.json"].read_text())
        selection = json.loads(paths["selection.json"].read_text())
        for name in ("installation.json", "selection.json"):
            shutil.copyfile(paths[name], out / name)
        validation.require(installation.get("operation") == "apt_install" and installation.get("status") == "passed" and
                           installation.get("architecture") == args.architecture and
                           installation.get("requested_execution_environment") == ENVIRONMENT,
                           "Invalid native installation receipt")
        validation.require(installation["base_sha256"] == validation.sha(paths["base.tar.gz"]) and
                           installation["rootfs_sha256"] == validation.sha(paths["rootfs.tar"]),
                           "Receipt is not bound to these input/output filesystems")
        validation.require(sorted(row["sha256"] for row in installation["input_packages"]) ==
                           sorted(row["source_sha256"] for row in selection["selected"]),
                           "Installed archives differ from the checked APT selection")
        validation.require({name.split(":")[0]: row["version"] for name, row in installation["installed_input_packages"].items()} ==
                           {row["package"]: row["version"] for row in selection["selected"]},
                           "Configured package versions differ from selection")
        report["installation"] = {"rootfs_sha256": installation["rootfs_sha256"], "base_sha256": installation["base_sha256"],
                                  "selected_packages": len(selection["selected"]),
                                  "installed_packages": len(installation["installed_packages"])}
        lock = validation.read_lock(ROOT / "tools/bazel/tests/dpkg_transactions.lock.json", args.architecture)
        repository = out / "packages"
        report["transaction_packages"] = validation.prepare_repository(lock, args.architecture, repository)
        sources = out / "sources.list"
        sources.write_text("# AUTO-GENERATED. DO NOT EDIT. Offline validation only.\ndeb [trusted=yes] file:/probe/packages ./\n")
        report["probes"] = {}
        for label, request in [
            ("initial-configuration", {"mode": "initial-configuration"}),
            ("install", {"mode": "install"}),
        ]:
            request.update(architecture=args.architecture, receipts=[], installed_receipts=[], lock=lock)
            with tempfile.TemporaryDirectory(prefix="configured-debian-probe-") as tmp:
                root = Path(tmp)
                execute(["bsdtar", "--extract", "--numeric-owner", "--preserve-permissions", "--file",
                         str(paths["rootfs.tar"]), "--directory", str(root)], name="extract-" + label)
                command = [str(paths["bwrap"]), "--die-with-parent", "--new-session", "--unshare-pid", "--unshare-net",
                    "--unshare-ipc", "--unshare-uts", "--cap-drop", "ALL"]
                for cap in ("CHOWN", "DAC_OVERRIDE", "FOWNER", "FSETID", "SETUID", "SETGID", "SETFCAP"):
                    command.extend(["--cap-add", "CAP_" + cap])
                command.extend(["--bind", str(root), "/", "--proc", "/proc", "--dev", "/dev",
                    "--perms", "01777", "--tmpfs", "/tmp",
                    "--perms", "0755", "--dir", "/probe",
                    "--ro-bind", str(repository), "/probe/packages",
                    "--ro-bind", str(sources), "/probe/sources.list",
                    "--ro-bind", str(ROOT / "tools/bazel/ci/validate_dpkg_state.py"), "/probe/validate.py",
                    "--clearenv", "--setenv", "PATH", "/usr/sbin:/usr/bin:/sbin:/bin", "--setenv", "LC_ALL", "C",
                    "--setenv", "DEBIAN_FRONTEND", "noninteractive", "--chdir", "/",
                    "/usr/bin/python3", "-B", "/probe/validate.py", "--in-container"])
                completed = subprocess.run(command, input=json.dumps(request), text=True, capture_output=True, timeout=600)
                (out / (label + ".log")).write_text(completed.stdout + completed.stderr)
                print(completed.stdout + completed.stderr, flush=True)
                lines = [line[len(validation.RESULT_PREFIX):] for line in completed.stdout.splitlines()
                         if line.startswith(validation.RESULT_PREFIX)]
                validation.require(len(lines) == 1, "Missing probe report: " + label)
                result = json.loads(lines[0])
                validation.write_json(out / (label + ".json"), result)
                report["probes"][label] = {"status": result["status"]}
                validation.require(completed.returncode == 0 and result["status"] == "passed", "Probe failed: " + label)
                validation.require({name: {"version": row["version"], "architecture": row["architecture"]}
                                    for name, row in result["installed"].items()} == installation["installed_packages"],
                                   "Probe inventory differs from installation receipt")
        report["status"] = "passed"
    except Exception as error:
        report.update(status="failed", error=str(error))
        raise
    finally:
        lockfile = ROOT / "MODULE.bazel.lock"
        if lockfile.exists():
            shutil.copyfile(lockfile, out / "MODULE.bazel.lock")
        validation.write_json(out / "receipt.json", report)


if __name__ == "__main__":
    main()
