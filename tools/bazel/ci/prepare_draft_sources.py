#!/usr/bin/env python3
"""Prepare reviewed source overrides while their registry PRs remain unmerged.

Registry endpoints in normal builds and CI remain main and BCR. This explicit
development step materializes exact registered source recipes, then emits the
same --override_module options for every CI build, query and test command.
Remove an entry when its registered version is available from main.
"""

import argparse
import base64
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shlex
import stat
import subprocess
from urllib.parse import quote
from urllib.request import urlopen


BAZELRC_HEADER = "# Generated by tools/bazel/ci/prepare_draft_sources.py; do not edit.\n"
GENERATED_NOTICE = "AUTO-GENERATED by tools/bazel/ci/prepare_draft_sources.py. DO NOT EDIT."


def require(value, message):
    if not value:
        raise ValueError(message)


def relative(value):
    path = PurePosixPath(value)
    require(value and str(path) == value and not path.is_absolute() and ".." not in path.parts,
            "invalid source path: " + value)
    return path


def verify(data, integrity):
    algorithm, encoded = integrity.split("-", 1)
    require(algorithm in ("sha256", "sha512"), "unsupported source digest")
    require(hashlib.new(algorithm, data).digest() == base64.b64decode(encoded, validate=True),
            "source integrity check failed")


def download(url, integrity=None):
    require(url.startswith("https://"), "source URL must use HTTPS")
    with urlopen(url, timeout=90) as response:
        data = response.read()
    if integrity:
        verify(data, integrity)
    return data


def tree_digest(directory):
    digest = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        name = path.relative_to(directory).as_posix()
        if path.is_symlink():
            require(path.resolve().is_relative_to(directory.resolve()), "source link leaves module: " + name)
            value = b"link\0" + os.readlink(path).encode()
        elif path.is_file():
            value = b"file\0" + path.read_bytes()
        else:
            continue
        digest.update(name.encode() + b"\0" + str(stat.S_IMODE(path.lstat().st_mode)).encode() +
                      b"\0" + hashlib.sha256(value).digest())
    return digest.hexdigest()


def recipe_attributes(name, registration):
    """Translate the registry recipe to its public http_archive attributes."""
    require(re.fullmatch(r"[a-zA-Z0-9_.+-]+", name), "invalid module name")
    version = registration["version"]
    require(re.fullmatch(r"[a-zA-Z0-9_.+-]+", version), "invalid module version")
    if "registry_commit" in registration:
        revision = registration["registry_commit"]
        require(re.fullmatch(r"[0-9a-f]{40}", revision), "registry source must use a full commit")
        prefix = "https://raw.githubusercontent.com/securely1g/sonic-bazel-registry/" + revision + "/modules/" + name + "/" + quote(version, safe="") + "/"
        recipe_data = download(prefix + "source.json", registration["source_json_integrity"])
        recipe = json.loads(recipe_data)
        origin = {"registry_commit": revision}
    else:
        revision = registration["source_commit"]
        require(re.fullmatch(r"[0-9a-f]{40}", revision), "source must use a full commit")
        recipe = registration["archive"]
        require(set(recipe) == {"url", "integrity", "strip_prefix"} and revision in recipe["url"],
                "unregistered source needs one pinned commit archive")
        recipe_data = json.dumps(recipe, sort_keys=True).encode()
        prefix = ""
        origin = {"source_commit": revision}
    require(recipe["url"].startswith("https://"), "source archive must use HTTPS")
    attributes = {
        "name": "draft_" + name.replace("-", "_").replace(".", "_"),
        "urls": [recipe["url"]], "integrity": recipe["integrity"],
        "strip_prefix": recipe.get("strip_prefix", ""),
        "remote_patches": {
            prefix + "patches/" + quote(str(relative(path)), safe="/"): integrity
            for path, integrity in recipe.get("patches", {}).items()
        },
        "remote_patch_strip": recipe.get("patch_strip", 0),
        "remote_file_urls": {
            str(relative(path)): [prefix + "overlay/" + quote(path, safe="/")]
            for path in recipe.get("overlay", {})
        },
        "remote_file_integrity": recipe.get("overlay", {}),
    }
    # Registry URLs may end in a commit rather than an archive suffix (for
    # example GitHub codeload). Preserve their explicit extraction format.
    if "archive_type" in recipe:
        attributes["type"] = recipe["archive_type"]
    receipt = {"_generated": GENERATED_NOTICE, "module": name, "version": version, **origin,
               "source_json_sha256": hashlib.sha256(recipe_data).hexdigest(),
               "http_archive": attributes}
    return attributes, receipt


def prepare(manifest_path, output, *, bazel="bazel", startup_args=(), bazel_args=()):
    manifest_data = manifest_path.read_bytes()
    manifest = json.loads(manifest_data)
    require(manifest.get("schema") == 1 and isinstance(manifest.get("modules"), dict), "invalid source manifest")
    generation = output.resolve() / hashlib.sha256(manifest_data).hexdigest()
    generation.mkdir(parents=True, exist_ok=True)
    receipts, attributes = {}, {}
    for name, registration in sorted(manifest["modules"].items()):
        attributes[name], receipts[name] = recipe_attributes(name, registration)
    # Preserve insertion order inside remote_patches: the native Bazel patcher
    # must apply the same ordered recipe as normal registry resolution.
    module = '# ' + GENERATED_NOTICE + '\nmodule(name = "reviewed_draft_sources")\n'
    module += 'http_archive = use_repo_rule("@bazel_tools//tools/build_defs/repo:http.bzl", "http_archive")\n'
    for item in attributes.values():
        module += "http_archive(\n" + "".join("    " + key + " = " + json.dumps(value) + ",\n"
                                             for key, value in item.items()) + ")\n"
    (generation / "MODULE.bazel").write_text(module)
    (generation / "BUILD.bazel").write_text("# " + GENERATED_NOTICE + "\n")
    # Bazelisk resolves its version from the subprocess working directory. The
    # preparation workspace must use the same release as the consuming checkout.
    bazel_version = Path(__file__).resolve().parents[3] / ".bazelversion"
    (generation / ".bazelversion").write_bytes(bazel_version.read_bytes())
    command = [bazel, "--ignore_all_rc_files", *startup_args,
               "--output_user_root=" + str(generation / "bazel")]
    flags = ["--registry=https://raw.githubusercontent.com/securely1g/sonic-bazel-registry/main",
             "--registry=https://bcr.bazel.build", *bazel_args]
    subprocess.run([*command, "fetch", *flags,
                    *["--repo=@" + item["name"] for item in attributes.values()]], cwd=generation, check=True)
    output_base = Path(subprocess.check_output([*command, "info", *flags, "output_base"], cwd=generation, text=True).strip())
    mapping = json.loads(subprocess.check_output([*command, "mod", "dump_repo_mapping", "", *flags],
                                                cwd=generation, text=True))
    overrides = []
    for name, item in attributes.items():
        destination = output_base / "external" / mapping[item["name"]]
        require((destination / "MODULE.bazel").is_file(), "prepared source lacks MODULE.bazel: " + name)
        receipt_path = generation / (name + ".receipt.json")
        digest = tree_digest(destination)
        if receipt_path.exists():
            previous = json.loads(receipt_path.read_text())
            require(previous["tree_sha256"] == digest, "prepared source was modified: " + name)
        receipts[name]["tree_sha256"] = digest
        receipt_path.write_text(json.dumps(receipts[name], sort_keys=True, indent=2) + "\n")
        overrides.append("--override_module=" + name + "=" + str(destination.resolve()))
    return {"_generated": GENERATED_NOTICE, "manifest_sha256": hashlib.sha256(manifest_data).hexdigest(),
            "overrides": overrides, "modules": receipts}


def write_bazelrc(path, result):
    """Use the existing ignored user RC hook for every command in this checkout."""
    require(not path.is_symlink(), "refusing to replace a Bazel RC symlink")
    if path.exists():
        require(path.read_text().startswith(BAZELRC_HEADER),
                "refusing to replace a manually maintained Bazel RC: " + str(path))
    arguments = result["overrides"]
    require(all(value.startswith("--override_module=") and "\n" not in value and "\r" not in value
                for value in arguments), "invalid prepared override option")
    contents = BAZELRC_HEADER + "# Source manifest SHA256: " + result["manifest_sha256"] + "\n"
    contents += "".join("common " + shlex.quote(value) + "\n" for value in arguments)
    path.write_text(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--receipt", required=True, type=Path)
    parser.add_argument("--bazelrc-output", type=Path,
                        help="write an ignored .bazelrc.user for all commands in this CI checkout")
    parser.add_argument("--bazel", default="bazel")
    parser.add_argument("--startup-arg", action="append", default=[])
    parser.add_argument("--bazel-arg", action="append", default=[])
    args = parser.parse_args()
    result = prepare(args.manifest, args.output, bazel=args.bazel,
                     startup_args=args.startup_arg, bazel_args=args.bazel_arg)
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps(result, sort_keys=True, indent=2) + "\n")
    if args.bazelrc_output:
        write_bazelrc(args.bazelrc_output, result)


if __name__ == "__main__":
    main()
