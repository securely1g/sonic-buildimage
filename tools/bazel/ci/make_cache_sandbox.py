#!/usr/bin/env python3
"""Scope the Make cache job's user-namespace allowance to its Bazel sandbox.

This uses PR #52's unconfined-profile/userns pattern for a disposable hosted
runner. It never changes the host-wide restriction or an administrator's policy.
"""

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import tempfile


SANDBOX = "/sonic/artifacts/private/bazel-install/linux-sandbox"
PROFILE_DIRECTORY = Path("/etc/apparmor.d")
PROFILES = Path("/sys/kernel/security/apparmor/profiles")
RESTRICTION = Path("/proc/sys/kernel/apparmor_restrict_unprivileged_userns")


def profile_name(job):
    if not re.fullmatch(r"[0-9]+-[0-9]+-(?:amd64|arm64)", job):
        raise ValueError("Use the GitHub run ID, attempt and native architecture for the profile name")
    return "sonic-make-cache-" + job


def profile_contents(job):
    return ("# AUTO-GENERATED by tools/bazel/ci/make_cache_sandbox.py. DO NOT EDIT.\n"
            "# Trusted disposable CI job; this is not a boundary for untrusted builds.\n"
            "abi <abi/4.0>,\ninclude <tunables/global>\n"
            f"profile {profile_name(job)} {SANDBOX} flags=(unconfined) {{\n"
            "  userns,\n}\n")


def restriction_value(path=RESTRICTION):
    try:
        value = path.read_text().strip()
    except FileNotFoundError:
        return None
    if value not in ("0", "1"):
        raise ValueError("Unexpected AppArmor user-namespace restriction value")
    return value


def loaded_profiles(path=PROFILES):
    return path.read_text().splitlines()


def check_managed_file(path, expected):
    info = path.lstat()
    if (not stat.S_ISREG(info.st_mode) or info.st_uid != 0 or info.st_mode & 0o022
            or path.read_text() != expected):
        raise ValueError("Refusing to remove changed or administrator-owned AppArmor policy")


def save_receipt(path, receipt):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")


def check_policy_directory(directory):
    info = directory.stat()
    if directory.is_symlink() or info.st_uid != 0 or info.st_mode & 0o022:
        raise ValueError("AppArmor policy directory must be root-owned and not group/world writable")


def install(job, receipt_path, *, directory=PROFILE_DIRECTORY, profiles=PROFILES, restriction=RESTRICTION):
    name = profile_name(job)
    contents = profile_contents(job)
    before = restriction_value(restriction)
    receipt = {"profile": name, "executable": SANDBOX, "installed": False,
               "restriction_before": before, "restriction_after": before,
               "global_policy_changed": False}
    save_receipt(receipt_path, receipt)
    if before != "1":
        return
    profile = directory / name
    if profile.exists() or profile.is_symlink() or any(
            row.startswith(name + " (") for row in loaded_profiles(profiles)):
        raise ValueError("Refusing to replace an existing AppArmor profile")
    check_policy_directory(directory)
    parser = shutil.which("apparmor_parser")
    if parser is None:
        raise ValueError("Install the apparmor package on the hosted runner")
    with tempfile.NamedTemporaryFile(mode="w", prefix="." + name + ".", dir=directory,
                                     delete=False) as output:
        staged = Path(output.name)
        output.write(contents)
    loaded = False
    try:
        subprocess.run([parser, "-Q", "-K", str(staged)], check=True)
        staged.chmod(0o644)
        os.chown(staged, 0, 0)
        receipt["install_started"] = True
        save_receipt(receipt_path, receipt)
        subprocess.run([parser, "-r", "-T", str(staged)], check=True)
        loaded = True
        os.replace(staged, profile)
        receipt.update(installed=True, profile_mode="unconfined")
        save_receipt(receipt_path, receipt)
        if name + " (unconfined)" not in loaded_profiles(profiles):
            raise ValueError("The job's sandbox AppArmor profile was not loaded")
        after = restriction_value(restriction)
        receipt["restriction_after"] = after
        save_receipt(receipt_path, receipt)
        if after != before:
            raise ValueError("Host-wide AppArmor namespace restriction changed during installation")
    except Exception:
        # Roll back even if receipt persistence or verification fails after the
        # profile file was installed. Never leave a loaded, untracked allowance.
        if loaded:
            policy = profile if profile.exists() else staged
            check_managed_file(policy, contents)
            subprocess.run([parser, "-R", str(policy)], check=True)
            if policy == profile:
                profile.unlink()
            receipt.update(installed=False, removed=True, installation_failed=True)
            try:
                save_receipt(receipt_path, receipt)
            except OSError:
                pass  # The policy was removed even if the workspace is unwritable.
        raise
    finally:
        staged.unlink(missing_ok=True)


def remove(job, receipt_path, *, directory=PROFILE_DIRECTORY, profiles=PROFILES, restriction=RESTRICTION):
    name = profile_name(job)
    if not receipt_path.exists():
        return
    receipt = json.loads(receipt_path.read_text())
    if receipt.get("profile") != name:
        raise ValueError("Sandbox cleanup receipt belongs to another job")
    if not (receipt.get("installed") or receipt.get("install_started")) or receipt.get("removed"):
        return
    profile = directory / name
    if not profile.exists() and not profile.is_symlink() and not any(
            row.startswith(name + " (") for row in loaded_profiles(profiles)):
        receipt["removed"] = True
        save_receipt(receipt_path, receipt)
        return
    check_managed_file(profile, profile_contents(job))
    parser = shutil.which("apparmor_parser")
    if parser is None:
        raise ValueError("AppArmor parser is missing during cleanup")
    subprocess.run([parser, "-R", str(profile)], check=True)
    if any(row.startswith(name + " (") for row in loaded_profiles(profiles)):
        raise ValueError("The job's sandbox AppArmor profile is still loaded")
    profile.unlink()
    receipt.update(removed=True, restriction_after_cleanup=restriction_value(restriction))
    save_receipt(receipt_path, receipt)
    if receipt["restriction_after_cleanup"] != receipt["restriction_before"]:
        raise ValueError("Host-wide AppArmor namespace restriction changed during the CI job")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("install", "remove"))
    parser.add_argument("--job", required=True)
    parser.add_argument("--receipt", required=True, type=Path)
    args = parser.parse_args()
    if (os.geteuid() != 0 or os.environ.get("GITHUB_ACTIONS") != "true"
            or os.environ.get("RUNNER_ENVIRONMENT") != "github-hosted" or Path("/.dockerenv").exists()):
        parser.error("Run this scoped setup as root only on the disposable GitHub-hosted runner")
    {"install": install, "remove": remove}[args.command](args.job, args.receipt)


if __name__ == "__main__":
    main()
